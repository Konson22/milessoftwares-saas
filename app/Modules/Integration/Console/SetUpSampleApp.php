<?php

namespace App\Modules\Integration\Console;

use App\Modules\Applications\Catalog\CatalogImporter;
use App\Modules\Applications\Models\Application;
use App\Modules\Entitlements\Actions\ManageEntitlements;
use App\Modules\Integration\Actions\ManageIntegration;
use App\Modules\Organizations\Models\OrganizationSlug;
use App\Support\Hosts\PlatformHosts;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;

/**
 * Registers examples/sample-app as a product (local development only):
 * catalog, sign-in client, service client, webhook endpoint, provisioning
 * endpoint, and writes the app's config.local.php with the secrets.
 */
class SetUpSampleApp extends Command
{
    protected $signature = 'platform:sample-app
        {--url=http://127.0.0.1:8200 : Where the sample app runs}
        {--finance-url=http://127.0.0.1:8300 : Where the reference Finance module runs}
        {--entitle= : Workspace slug of an organization to entitle to the sample product}
        {--fresh : Register new clients even if a config already exists}';

    protected $description = 'Register the bundled sample product and reference Finance module for local end-to-end testing';

    public function handle(CatalogImporter $catalogs, ManageIntegration $integration, ManageEntitlements $entitlements): int
    {
        if (app()->isProduction()) {
            $this->components->error('The sample app is for local development only.');

            return self::FAILURE;
        }

        $base = rtrim((string) $this->option('url'), '/');
        $configPath = base_path('examples/sample-app/config.local.php');

        $definition = json_decode((string) file_get_contents(base_path('examples/sample-app/catalog.json')), true, flags: JSON_THROW_ON_ERROR);
        $catalogs->import($definition);
        $application = Application::query()->where('code', 'sample')->sole();

        if (! is_file($configPath) || $this->option('fresh')) {
            DB::table('application_clients')->where('application_id', $application->id)->get()
                ->each(fn (object $row) => $integration->disableClient($application, $row->id, null));

            $signIn = $integration->registerSignInClient($application, 'Sample product web', true, ["{$base}/callback"], null, null);
            $service = $integration->registerServiceClient($application, 'Sample product backend', null);
            $webhookSecret = $integration->configureWebhook($application, "{$base}/webhooks", true, null);

            $config = [
                'issuer' => PlatformHosts::url(PlatformHosts::auth()),
                'backchannel' => (string) (config('platform.oidc.backchannel_url') ?: PlatformHosts::url(PlatformHosts::auth())),
                'client_id' => $signIn['client_id'],
                'client_secret' => (string) $signIn['client_secret'],
                'redirect_uri' => "{$base}/callback",
                'service_client_id' => $service['client_id'],
                'service_client_secret' => (string) $service['client_secret'],
                'webhook_secret' => (string) $webhookSecret,
                'finance_url' => rtrim((string) $this->option('finance-url'), '/'),
            ];

            file_put_contents($configPath, "<?php\n\n// Generated by `php artisan platform:sample-app`. Holds secrets; never commit.\nreturn ".var_export($config, true).";\n");
            $this->components->info('Registered the sample product and wrote examples/sample-app/config.local.php.');
        } else {
            $this->components->info('Sample product already registered (use --fresh to issue new clients).');
        }

        $finance = $this->registerFinanceModule($catalogs, $integration);

        $application->forceFill([
            'provisioning_method' => 'sync_api',
            'integration_endpoint' => "{$base}/platform",
            // Never on the public site.
            'capabilities' => [...(array) ($application->capabilities ?? []), 'marketing' => ['unlisted' => true]],
        ])->save();

        if (is_string($slug = $this->option('entitle')) && $slug !== '') {
            $organization = OrganizationSlug::query()->where('slug', $slug)->where('is_primary', true)->first()?->organization;

            if ($organization === null) {
                $this->components->error("No organization with the workspace address [{$slug}].");

                return self::FAILURE;
            }

            $entitlements->grantManual($organization, $application, null, 'Local sample app testing');
            $entitlements->grantManual($organization, $finance, null, 'Local reference Finance module testing');
            $this->components->info("{$organization->display_name} is entitled to the sample product and the reference Finance module.");
        }

        $this->line('Run: php -S 127.0.0.1:8200 -t examples/sample-app/public  and  php -S 127.0.0.1:8300 -t examples/finance-module/public');
        $this->line("Then open {$base}/login?org=<slug>");

        return self::SUCCESS;
    }

    /**
     * The reference shared module: catalog, a service client for health
     * reports, and examples/finance-module/config.local.php.
     */
    private function registerFinanceModule(CatalogImporter $catalogs, ManageIntegration $integration): Application
    {
        $catalogs->import(json_decode((string) file_get_contents(base_path('examples/finance-module/catalog.json')), true, flags: JSON_THROW_ON_ERROR));
        $finance = Application::query()->where('code', 'finance')->sole();
        $finance->forceFill(['capabilities' => [...(array) ($finance->capabilities ?? []), 'marketing' => ['unlisted' => true]]])->save();

        $configPath = base_path('examples/finance-module/config.local.php');

        if (! is_file($configPath) || $this->option('fresh')) {
            $service = $integration->registerServiceClient($finance, 'Finance module backend', null);

            file_put_contents($configPath, '<?php

// Generated by `php artisan platform:sample-app`. Holds secrets; never commit.
return '.var_export([
                'issuer' => PlatformHosts::url(PlatformHosts::auth()),
                'backchannel' => (string) (config('platform.oidc.backchannel_url') ?: PlatformHosts::url(PlatformHosts::auth())),
                'service_client_id' => $service['client_id'],
                'service_client_secret' => (string) $service['client_secret'],
            ], true).';
');
            $this->components->info('Registered the reference Finance module and wrote examples/finance-module/config.local.php.');
        }

        return $finance;
    }
}
